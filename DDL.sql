CREATE TABLE IF NOT EXISTS Customer (
    customer_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_type   VARCHAR(20) NOT NULL CHECK (customer_type IN ('individual', 'organization')),
    customer_name   VARCHAR(100) NOT NULL,
    city            VARCHAR(50) NOT NULL,
    id_type         VARCHAR(25) NOT NULL CHECK (id_type IN ('identity_card', 'passport', 'business_registration')),
    id_no           VARCHAR(20) NOT NULL,
    kyc_status      VARCHAR(20) NOT NULL CHECK (kyc_status IN ('pending', 'verified', 'rejected')) DEFAULT 'pending',
    customer_status VARCHAR(20) NOT NULL CHECK (customer_status IN ('active', 'blocked', 'closed')) DEFAULT 'active',
    registered_date DATE NOT NULL DEFAULT CURRENT_DATE,

    UNIQUE (id_type, id_no),
    CHECK (customer_type = 'individual' AND id_type IN ('identity_card', 'passport') OR
           customer_type = 'organization' AND id_type = 'business_registration')
);

CREATE TABLE IF NOT EXISTS Partner (
    partner_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partner_name    VARCHAR(100) NOT NULL,
    partner_type    VARCHAR(20) NOT NULL CHECK (partner_type IN ('biller', 'bank', 'remittance_partner', 'fund_distributor')),
    partner_status  VARCHAR(20) NOT NULL CHECK (partner_status IN ('active', 'suspended', 'terminated')) DEFAULT 'active',
    sector          VARCHAR(50) NOT NULL CHECK (sector IN ('electricity', 'water', 'telecommunication', 'insurance',
                          'banking', 'pension', 'social_welfare', 'other'))
);


CREATE TABLE IF NOT EXISTS Account (
    account_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_no      VARCHAR(20) NOT NULL UNIQUE,
    account_name    VARCHAR(100) NOT NULL,
    opened_date     DATE NOT NULL DEFAULT CURRENT_DATE,
    account_status  VARCHAR(20) NOT NULL CHECK (account_status IN ('active', 'dormant', 'closed')) DEFAULT 'active',
    current_balance NUMERIC(20, 6) NOT NULL DEFAULT 0 CHECK (current_balance >= 0),
    customer_id     BIGINT NOT NULL,

    FOREIGN KEY (customer_id) REFERENCES Customer(customer_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS Transaction (
    transaction_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_type        VARCHAR(20) NOT NULL CHECK (transaction_type IN ('account', 'bill_payment', 'remittance', 'disbursement')),
    transaction_datetime    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    amount                  NUMERIC(20, 6) NOT NULL CHECK (amount > 0),
    currency_code           VARCHAR(3) NOT NULL CHECK (currency_code IN ('USD', 'EUR', 'GBP', 'JPY', 'CNY', 'SGD', 'IDR')) DEFAULT 'IDR',
    reference_no            VARCHAR(20) NOT NULL UNIQUE,
    balance_before          NUMERIC(20, 6) CHECK (balance_before >= 0),
    balance_after           NUMERIC(20, 6) CHECK (balance_after >= 0),
    customer_id             BIGINT,
    account_id              BIGINT,

    FOREIGN KEY (customer_id) REFERENCES Customer(customer_id),
    FOREIGN KEY (account_id) REFERENCES Account(account_id),

    CHECK ((account_id IS NULL AND balance_before IS NULL AND balance_after IS NULL) OR (account_id IS NOT NULL AND balance_before IS NOT NULL AND balance_after IS NOT NULL)),
    CHECK (transaction_type <> 'account' OR account_id IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS Account_Transaction (
    transaction_id              BIGINT PRIMARY KEY,
    movement_type               VARCHAR(20) NOT NULL CHECK (movement_type IN ('deposit', 'withdrawal', 'transfer')),
    counterparty_account_no    VARCHAR(20),

    FOREIGN KEY (transaction_id) REFERENCES Transaction(transaction_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS Bill (
    bill_id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    biller_customer_no  VARCHAR(30) NOT NULL,
    billing_period      DATE NOT NULL,
    bill_amount         NUMERIC(20, 6) NOT NULL CHECK (bill_amount > 0),
    penalty_amount      NUMERIC(20, 6) NOT NULL DEFAULT 0 CHECK (penalty_amount >= 0),
    due_date            DATE NOT NULL,
    bill_status         VARCHAR(10) NOT NULL CHECK (bill_status IN ('unpaid', 'paid')) DEFAULT 'unpaid',
    partner_id          BIGINT NOT NULL,

    FOREIGN KEY (partner_id) REFERENCES Partner(partner_id),
    UNIQUE (partner_id, biller_customer_no, billing_period)
);

CREATE TABLE IF NOT EXISTS Bill_Payment (
    transaction_id      BIGINT PRIMARY KEY,
    payment_method      VARCHAR(20) NOT NULL CHECK (payment_method IN ('cash', 'giro', 'electronic_money', 'other')),
    biller_reference_no VARCHAR(40),
    confirmed_datetime  TIMESTAMP,
    bill_id             BIGINT NOT NULL,

    FOREIGN KEY (transaction_id) REFERENCES Transaction(transaction_id) ON DELETE CASCADE,
    FOREIGN KEY (bill_id) REFERENCES Bill(bill_id)
);

CREATE TABLE IF NOT EXISTS Remittance (
    transaction_id              BIGINT PRIMARY KEY,
    service_scope               VARCHAR(20) NOT NULL CHECK (service_scope IN ('domestic', 'international')),
    destination_country_code    CHAR(2) NOT NULL DEFAULT 'ID',
    delivery_method             VARCHAR(20) NOT NULL CHECK (delivery_method IN ('cash_pickup', 'bank_account')),
    purpose                     VARCHAR(100),

    FOREIGN KEY (transaction_id) REFERENCES Transaction(transaction_id) ON DELETE CASCADE  
);

CREATE TABLE IF NOT EXISTS Disbursement (
    transaction_id      BIGINT PRIMARY KEY,
    disbursement_method VARCHAR(20) NOT NULL CHECK (disbursement_method IN ('cash', 'account_credit')),
    verification_method VARCHAR(20) NOT NULL CHECK (verification_method in ('identity_card', 'collection_code', 'biometric')),
    verified_id_no      VARCHAR(20),

    FOREIGN KEY (transaction_id) REFERENCES Transaction(transaction_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS Status_History (
    transaction_id  BIGINT NOT NULL,
    sequence_no     SMALLINT NOT NULL CHECK (sequence_no >= 1),
    status          VARCHAR(20) NOT NULL CHECK (status IN ('initiated', 'processing', 'success', 'failed', 'reversed')),
    status_datetime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reason_code     VARCHAR(30),

    PRIMARY KEY (transaction_id, sequence_no),
    FOREIGN KEY (transaction_id) REFERENCES Transaction(transaction_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS Transaction_Fee (
    transaction_id  BIGINT NOT NULL,
    fee_no          SMALLINT NOT NULL CHECK (fee_no >= 1),
    fee_type        VARCHAR(20) NOT NULL CHECK (fee_type IN ('admin', 'service','tax', 'other')),
    fee_amount      NUMERIC(20, 6) NOT NULL CHECK (fee_amount >= 0),
    charged_to      VARCHAR(20) NOT NULL CHECK (charged_to IN ('customer', 'partner')),
    
    PRIMARY KEY (transaction_id, fee_no),
    FOREIGN KEY (transaction_id) REFERENCES Transaction(transaction_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS Receipt (
    receipt_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issued_datetime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delivery_format VARCHAR(10) NOT NULL CHECK (delivery_format IN ('printed', 'digital')),
    reprint_count   SMALLINT NOT NULL DEFAULT 0 CHECK( reprint_count >= 0),
    transaction_id  BIGINT NOT NULL UNIQUE,

    FOREIGN KEY (transaction_id) REFERENCES Transaction(transaction_id)
);

CREATE TABLE IF NOT EXISTS Money_Order(
    money_order_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collection_code VARCHAR(20) NOT NULL UNIQUE,
    receiver_name   VARCHAR(100) NOT NULL,
    order_amount    NUMERIC(20, 6) NOT NULL CHECK (order_amount > 0),
    expiry_date     DATE NOT NULL,
    order_status    VARCHAR(20) NOT NULL CHECK (order_status IN ('issued', 'cashed', 'expired', 'cancelled')) DEFAULT 'issued',
    transaction_id  BIGINT NOT NULL UNIQUE,

    FOREIGN KEY (transaction_id) REFERENCES Remittance(transaction_id)
);

CREATE TABLE IF NOT EXISTS Money_Order_Receiver_Phone (
    money_order_id BIGINT NOT NULL,
    receiver_phone VARCHAR(20) NOT NULL,

    PRIMARY KEY (money_order_id, receiver_phone),
    FOREIGN KEY (money_order_id) REFERENCES Money_Order(money_order_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS Fund_Distribution_Program (
    program_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_name    VARCHAR(100) NOT NULL,
    program_type    VARCHAR(30) NOT NULL CHECK (program_type IN ('social_assistance', 'pension', 'commercial', 'other')),
    start_date      DATE NOT NULL,
    end_date        DATE NOT NULL,
    total_budget    NUMERIC(20,6) NOT NULL CHECK (total_budget > 0),
    program_status  VARCHAR(20) NOT NULL CHECK (program_status IN ('planned', 'active', 'closed')) DEFAULT 'planned',
    partner_id      BIGINT NOT NULL,

    FOREIGN KEY (partner_id) REFERENCES Partner(partner_id),
    CHECK (end_date >= start_date)
);

CREATE TABLE IF NOT EXISTS Payout (
    payout_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receiver_name   VARCHAR(100) NOT NULL,
    receiver_id_no  VARCHAR(20),
    payout_amount   NUMERIC(20,6) NOT NULL CHECK (payout_amount > 0),
    payout_datetime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    transaction_id  BIGINT NOT NULL UNIQUE,
    money_order_id  BIGINT UNIQUE,
    program_id      BIGINT,

    FOREIGN KEY (transaction_id) REFERENCES Disbursement(transaction_id),
    FOREIGN KEY (money_order_id) REFERENCES Money_Order(money_order_id),
    FOREIGN KEY (program_id) REFERENCES Fund_Distribution_Program(program_id)
);

CREATE TABLE IF NOT EXISTS Reversal (
    reversal_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reversal_datetime   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reason_code         VARCHAR(20) NOT NULL CHECK (reason_code In  ('timeout', 'wrong_input', 'duplicate', 'other')),
    reversed_amount     NUMERIC (20, 6) NOT NULL CHECK (reversed_amount > 0),
    reversal_status     VARCHAR(20) NOT NULL CHECK (reversal_status IN ('requested', 'completed', 'rejected')) DEFAULT 'requested',
    transaction_id      BIGINT NOT NULL,

    FOREIGN KEY (transaction_id) REFERENCES Bill_Payment(transaction_id)
);